//! Generates the data model tables from the Matter IDL that rs-matter ships
//! (the CSA's `controller-clusters.matter`, the same file the C++ SDK and
//! rs-matter generate their cluster code from). Nothing here is typed by hand:
//! a new rs-matter pin brings a new Matter revision's clusters with it.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use rs_matter_codegen::ast::{Cluster, DataType, Entities, Idl, StructField, StructType};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let idl = rs_matter_codegen::parse_idl();
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("model.rs");
    std::fs::write(out, Gen::new(&idl).run()).unwrap();
}

struct Gen<'a> {
    idl: &'a Idl,
    out: String,
    unknown: HashSet<String>,
}

/// Where an entity was declared: in a cluster (by its code) or globally.
#[derive(Clone, Copy)]
enum Scope {
    Cluster(u64),
    Global,
}

impl Scope {
    fn ident(self, kind: &str, name: &str) -> String {
        match self {
            Scope::Cluster(code) => format!("C{code:04X}_{kind}_{name}"),
            Scope::Global => format!("G_{kind}_{name}"),
        }
    }
}

impl<'a> Gen<'a> {
    fn new(idl: &'a Idl) -> Self {
        Self {
            idl,
            out: String::new(),
            unknown: HashSet::new(),
        }
    }

    fn run(mut self) -> String {
        self.out.push_str(
            "// Generated by build.rs from rs-matter's copy of the Matter IDL. Do not edit.\n\n",
        );

        self.entities(&self.idl.globals, Scope::Global);

        let mut clusters: BTreeMap<u64, &Cluster> = BTreeMap::new();
        for cluster in &self.idl.clusters {
            clusters.entry(cluster.code).or_insert(cluster);
        }

        for cluster in clusters.values() {
            self.entities(&cluster.entities, Scope::Cluster(cluster.code));
            self.events(cluster);
        }

        self.out.push_str(
            "/// Every cluster of the IDL, sorted by id.\npub static CLUSTERS: &[Cluster] = &[\n",
        );
        for cluster in clusters.values() {
            let body = self.cluster(cluster);
            self.out.push_str(&body);
        }
        self.out.push_str("];\n");

        let mut unknown: Vec<_> = self.unknown.iter().collect();
        unknown.sort();
        for name in unknown {
            println!("cargo:warning=matter-model: IDL type `{name}` has no JSON mapping; values of it are converted by their TLV type");
        }

        self.out
    }

    fn entities(&mut self, entities: &Entities, scope: Scope) {
        for e in &entities.enums {
            let mut s = format!(
                "#[allow(non_upper_case_globals, dead_code)]\nstatic {}: EnumDef = EnumDef {{ name: {:?}, values: &[",
                scope.ident("E", &e.id),
                e.id
            );
            for entry in &e.entries {
                let _ = write!(s, "({}, {:?}), ", entry.code, entry.id);
            }
            s.push_str("] };\n");
            self.out.push_str(&s);
        }

        for b in &entities.bitmaps {
            let mut s = format!(
                "#[allow(non_upper_case_globals, dead_code)]\nstatic {}: BitmapDef = BitmapDef {{ name: {:?}, bits: &[",
                scope.ident("B", &b.id),
                b.id
            );
            for entry in &b.entries {
                let _ = write!(s, "({}, {:?}), ", entry.code, entry.id);
            }
            s.push_str("] };\n");
            self.out.push_str(&s);
        }

        for st in &entities.structs {
            let fields = self.fields(&st.fields, scope);
            let s = format!(
                "#[allow(non_upper_case_globals, dead_code)]\nstatic {}: StructDef = StructDef {{ name: {:?}, fields: &[{}], fabric_scoped: {} }};\n",
                scope.ident("S", &st.id),
                st.id,
                fields,
                st.is_fabric_scoped,
            );
            self.out.push_str(&s);
        }
    }

    fn events(&mut self, c: &Cluster) {
        let scope = Scope::Cluster(c.code);
        for e in &c.events {
            let fields = self.fields(&e.fields, scope);
            let def = format!(
                "#[allow(non_upper_case_globals, dead_code)]\nstatic {}: StructDef = StructDef {{ name: {:?}, fields: &[{}], fabric_scoped: {} }};\n",
                scope.ident("EV", &e.id),
                e.id,
                fields,
                e.is_fabric_sensitive,
            );
            self.out.push_str(&def);
        }
    }

    fn fields(&mut self, fields: &[StructField], scope: Scope) -> String {
        let mut sorted: Vec<&StructField> = fields.iter().collect();
        sorted.sort_by_key(|f| f.field.code);

        let mut s = String::new();
        for f in sorted {
            let ty = self.ty(&f.field.data_type, scope);
            let _ = write!(
                s,
                "Field {{ tag: {}, name: {:?}, ty: {}, list: {}, nullable: {}, optional: {} }}, ",
                f.field.code,
                f.field.id,
                ty,
                f.field.data_type.is_list,
                f.is_nullable,
                f.is_optional,
            );
        }
        s
    }

    /// The `Type` expression for an IDL data type, resolving names to the
    /// cluster's own entities first and then to the global ones.
    fn ty(&mut self, dt: &DataType, scope: Scope) -> String {
        let name = dt.name.as_str();

        if let Some(prim) = primitive(&name.to_ascii_lowercase()) {
            return prim.to_string();
        }

        let lookup = |entities: &Entities, s: Scope| -> Option<String> {
            if entities.enums.iter().any(|e| e.id == name) {
                Some(format!("Type::Enum(&{})", s.ident("E", name)))
            } else if entities.bitmaps.iter().any(|b| b.id == name) {
                Some(format!("Type::Bitmap(&{})", s.ident("B", name)))
            } else if entities.structs.iter().any(|st| st.id == name) {
                Some(format!("Type::Struct(&{})", s.ident("S", name)))
            } else {
                None
            }
        };

        if let Scope::Cluster(code) = scope {
            let cluster = self.idl.clusters.iter().find(|c| c.code == code).unwrap();
            if let Some(t) = lookup(&cluster.entities, scope) {
                return t;
            }
        }

        if let Some(t) = lookup(&self.idl.globals, Scope::Global) {
            return t;
        }

        self.unknown.insert(name.to_string());
        format!("Type::Unknown({name:?})")
    }

    fn cluster(&mut self, c: &Cluster) -> String {
        let scope = Scope::Cluster(c.code);

        let mut s = format!(
            "    Cluster {{ id: {}, name: {:?}, revision: {}, attributes: &[",
            c.code, c.id, c.revision
        );

        let mut attrs: Vec<_> = c.attributes.iter().collect();
        attrs.sort_by_key(|a| a.field.field.code);
        for a in attrs {
            let ty = self.ty(&a.field.field.data_type, scope);
            let _ = write!(
                s,
                "Attribute {{ id: {}, name: {:?}, ty: {}, list: {}, nullable: {}, optional: {}, writable: {}, timed_write: {} }}, ",
                a.field.field.code,
                a.field.field.id,
                ty,
                a.field.field.data_type.is_list,
                a.field.is_nullable,
                a.field.is_optional,
                !a.is_read_only,
                a.is_timed_write,
            );
        }

        s.push_str("], commands: &[");
        let mut cmds: Vec<_> = c.commands.iter().collect();
        cmds.sort_by_key(|cmd| cmd.code);
        for cmd in cmds {
            let request = match &cmd.input {
                Some(name) => self.struct_ref(c, name),
                None => "None".to_string(),
            };
            let response = if cmd.output == "DefaultSuccess" {
                "None".to_string()
            } else {
                self.struct_ref(c, &cmd.output)
            };
            let _ = write!(
                s,
                "Command {{ id: {}, name: {:?}, request: {}, response: {}, timed: {} }}, ",
                cmd.code, cmd.id, request, response, cmd.is_timed
            );
        }

        s.push_str("], events: &[");
        let mut events: Vec<_> = c.events.iter().collect();
        events.sort_by_key(|e| e.code);
        for e in events {
            let _ = write!(
                s,
                "Event {{ id: {}, name: {:?}, payload: &{} }}, ",
                e.code,
                e.id,
                scope.ident("EV", &e.id)
            );
        }

        s.push_str("], responses: &[");
        for st in &c.entities.structs {
            if let StructType::Response(code) = st.struct_type {
                let _ = write!(s, "({}, &{}), ", code, scope.ident("S", &st.id));
            }
        }
        s.push_str("] },\n");
        s
    }

    fn struct_ref(&self, c: &Cluster, name: &str) -> String {
        if c.entities.structs.iter().any(|st| st.id == name) {
            format!("Some(&{})", Scope::Cluster(c.code).ident("S", name))
        } else if self.idl.globals.structs.iter().any(|st| st.id == name) {
            format!("Some(&{})", Scope::Global.ident("S", name))
        } else {
            "None".to_string()
        }
    }
}

/// The IDL's primitive and semantic types, by signedness and encoding: the
/// TLV width of an integer is chosen from its value, as the spec allows.
fn primitive(name: &str) -> Option<&'static str> {
    Some(match name {
        "boolean" => "Type::Bool",
        "single" => "Type::Float",
        "double" => "Type::Double",
        "char_string" | "long_char_string" => "Type::String",
        "octet_string" | "long_octet_string" | "ipadr" | "ipv4adr" | "ipv6adr" | "ipv6pre"
        | "hwadr" => "Type::Octets",
        "int8s" | "int16s" | "int24s" | "int32s" | "int40s" | "int48s" | "int56s" | "int64s"
        | "temperature" | "amperage_ma" | "voltage_mv" | "power_mw" | "power_mva"
        | "power_mvar" | "energy_mwh" | "energy_mvah" | "energy_mvarh" | "money" => "Type::Int",
        "int8u" | "int16u" | "int24u" | "int32u" | "int40u" | "int48u" | "int56u" | "int64u"
        | "enum8" | "enum16" | "bitmap8" | "bitmap16" | "bitmap32" | "bitmap64" | "percent"
        | "percent100ths" | "epoch_us" | "epoch_s" | "utc" | "date" | "tod" | "elapsed_s"
        | "fabric_id" | "node_id" | "vendor_id" | "devtype_id" | "group_id" | "endpoint_no"
        | "cluster_id" | "attrib_id" | "field_id" | "event_id" | "command_id" | "action_id"
        | "trans_id" | "data_ver" | "event_no" | "fabric_idx" | "entry_idx" | "status"
        | "priority" | "posix_ms" | "systime_us" | "systime_ms" | "subject_id" => "Type::Uint",
        _ => return None,
    })
}
